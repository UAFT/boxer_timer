import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {clonePreset} from '../app/js/state/presets.js';
import {compileProgram} from '../app/js/core/program.js';
import {editorProgramIdentity,programHeading,programDurationSec,syncEditorProgramHeader} from '../app/js/ui/program-presentation.js';
const profiles={classic3:clonePreset('classic3'),classic2:clonePreset('classic2'),classic1:clonePreset('classic1'),tabata2020x24:clonePreset('tabata2020x24')};
const first={presetId:'classic3',title:'Кардио — Скакалка 3 × 3',settings:{...profiles.classic3,rounds:3,workSec:180,restSec:60},restAfterSec:120};
const second={presetId:'classic2',title:'Бокс — Комплекс 1',settings:{...profiles.classic2,rounds:2,workSec:60,restSec:30},restAfterSec:0};
const saved=[{id:'existing',name:'Программа 1',entries:[first],options:{cycles:1,cycleRestSec:60}}];
test('existing saved program identity stays available for explicit overwrite after appending stage',()=>{
 const match=editorProgramIdentity('existing',saved);
 assert.equal(match,saved[0]);
 const edited=[...match.entries,second];
 assert.equal(editorProgramIdentity('existing',saved)?.id,'existing');
 assert.equal(saved[0].entries.length,1,'unchanged saved program until update');
 assert.ok(programDurationSec(edited,profiles,match.options)>programDurationSec(saved[0].entries,profiles,match.options));
 assert.equal(editorProgramIdentity(null,saved),null);
});
test('program panel duration exactly matches compiled rounds including inter-stage and inter-cycle rests',()=>{
 const stages=[first,second],options={cycles:2,cycleRestSec:90};
 const rows=compileProgram(stages,profiles,options);
 assert.equal(programDurationSec(stages,profiles,options),rows.reduce((n,r)=>n+r.workSec+r.restSec+(r.blockRestSec||0),0));
 const heading=programHeading('Программа 1',stages,profiles,options,'ru');
 assert.equal(heading.name,'Программа 1');
 assert.ok(heading.duration.endsWith('минут') || heading.duration.includes('минут'));
 assert.deepEqual(programHeading('',[],profiles,options),{name:'',duration:'',visible:false});
 const empty=programHeading('',stages,profiles,options);
 assert.equal(empty.name,'Новая программа');
});
test('editor heading displays name and time, remains visible after appending unsaved stage, clears on removal',()=>{
 const elements={programActiveInfo:{hidden:true},programCurrentName:{textContent:''},programCurrentDuration:{textContent:''}};
 const doc={getElementById:id=>elements[id]};
 syncEditorProgramHeader(doc,{name:'Программа 1',entries:[first],profiles,options:{cycles:1}});
 assert.equal(elements.programActiveInfo.hidden,false);
 assert.equal(elements.programCurrentName.textContent,'Программа 1');
 assert.ok(elements.programCurrentDuration.textContent.startsWith('— '),'time is separated by an em dash');
 const old=elements.programCurrentDuration.textContent;
 syncEditorProgramHeader(doc,{name:'Программа 1',entries:[first,second],profiles,options:{cycles:1}});
 assert.notEqual(elements.programCurrentDuration.textContent,old);
 syncEditorProgramHeader(doc,{name:'',entries:[],profiles,options:{cycles:1}});
 assert.equal(elements.programActiveInfo.hidden,true);
});
